#define CMDI_CHARACTER_MEMORY_DATA_IN        0x0B
#define CMDI_CHARACTER_MEMORY_DATA_IN_READ   (CMDI_CHARACTER_MEMORY_DATA_IN | READ_OFFSET)

// OSD
#define OSDM_OSD_INSERTION_MUX               0x0C
