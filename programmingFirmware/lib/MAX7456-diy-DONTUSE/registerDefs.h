#define VOS_VERTICAL_OFFSET                  0x03
#define VOS_VERTICAL_OFFSET_READ             (VOS_VERTICAL_OFFSET | READ_OFFSET)

// Display Memory
#define DMM_DISPLAY_MEMORY_MODE              0x04
#define DMM_DISPLAY_MEMORY_MODE_READ         (DMM_DISPLAY_MEMORY_MODE | READ_OFFSET)

#define DMAH_DISPLAY_MEMORY_ADDRESS_HIGH     0x05
#define DMAH_DISPLAY_MEMORY_ADDRESS_HIGH_READ (DMAH_DISPLAY_MEMORY_ADDRESS_HIGH | READ_OFFSET)

#define DMAL_DISPLAY_MEMORY_ADDRESS_LOW      0x06
#define DMAL_DISPLAY_MEMORY_ADDRESS_LOW_READ (DMAL_DISPLAY_MEMORY_ADDRESS_LOW | READ_OFFSET)

#define DMDI_DISPLAY_MEMORY_DATA_IN          0x07
#define DMDI_DISPLAY_MEMORY_DATA_IN_READ     (DMDI_DISPLAY_MEMORY_DATA_IN | READ_OFFSET)

// Character Memory
#define CMM_CHARACTER_MEMORY_MODE            0x08
#define CMM_CHARACTER_MEMORY_MODE_READ       (CMM_CHARACTER_MEMORY_MODE | READ_OFFSET)

#define CMAH_CHARACTER_MEMORY_ADDRESS_HIGH   0x09
#define CMAH_CHARACTER_MEMORY_ADDRESS_HIGH_READ (CMAH_CHARACTER_MEMORY_ADDRESS_HIGH | READ_OFFSET)

#define CMAL_CHARACTER_MEMORY_ADDRESS_LOW    0x0A
